-- ---------------------------------------------------------------------
-- 3) FUNCIONARIOS_AFASTAMENTOS — histórico de afastamentos (S-2230).
-- Não temos a Tabela 18 oficial (motivos de afastamento) fornecida,
-- então uso uma classificação própria enxuta em vez de inventar
-- códigos numéricos que não são reais.
-- ---------------------------------------------------------------------

create table if not exists funcionarios_afastamentos (
  id uuid primary key default gen_random_uuid(),
  empresa_id uuid not null references empresas(id) on delete cascade,
  funcionario_id uuid not null references funcionarios(id) on delete cascade,
  data_inicio date not null,
  data_fim date,
  motivo varchar(25) not null
    check (motivo in ('acidente_trabalho', 'doenca_ocupacional', 'doenca_nao_ocupacional', 'outros')),
  cid10_codigo varchar(4) references cid10(codigo),
  observacao text,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  constraint chk_afastamento_vigencia check (data_fim is null or data_fim >= data_inicio)
);

-- No máximo um afastamento aberto (vigente) por funcionário.
drop index if exists idx_funcionarios_afastamentos_aberto;
create unique index idx_funcionarios_afastamentos_aberto
  on funcionarios_afastamentos (funcionario_id)
  where data_fim is null;

create index if not exists idx_funcionarios_afastamentos_empresa on funcionarios_afastamentos(empresa_id);
create index if not exists idx_funcionarios_afastamentos_funcionario
  on funcionarios_afastamentos(funcionario_id, data_inicio desc);

drop trigger if exists trg_funcionarios_afastamentos_atualizado on funcionarios_afastamentos;
create trigger trg_funcionarios_afastamentos_atualizado before update on funcionarios_afastamentos
  for each row execute function public.set_atualizado_em();

alter table funcionarios_afastamentos enable row level security;

drop policy if exists funcionarios_afastamentos_select on funcionarios_afastamentos;
